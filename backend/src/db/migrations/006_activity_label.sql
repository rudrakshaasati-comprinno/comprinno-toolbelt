-- 006_activity_label.sql — make the agent activity timeline emergent.
--
-- The activity timeline should reflect WHAT THE AGENT ACTUALLY DID (real tool
-- calls / step names it emits), not a fixed set of predefined phases. Research
-- (AG-UI protocol; Claude Code / LangGraph activity models; the
-- "agent-as-business-process" anti-pattern) converges on emergent activity
-- labels rather than a closed enum.
--
-- This drops the CHECK-constrained `phase` column on agent_activity and renames
-- it to a free-form `label`. Existing values (goal/gather/analyze/...) remain
-- valid free text — no data loss.
--
-- NOTE: the enums on requirements/recommendations/proposal_sections (status,
-- confidence, 7R strategy) are deliberately UNCHANGED — those are the validated
-- output contract, not "what the agent is doing".

BEGIN;

-- Drop the phase enum CHECK, then rename the column. The CHECK constraint name
-- is auto-generated by Postgres as <table>_<column>_check.
ALTER TABLE agent_activity DROP CONSTRAINT IF EXISTS agent_activity_phase_check;
ALTER TABLE agent_activity RENAME COLUMN phase TO label;

COMMIT;
